package tw.captions.desktop

import java.io.File
import java.time.LocalDate
import java.util.Locale

/**
 * `--hotwords-test`: the user's custom vocabulary (自訂詞彙) as sherpa-onnx hotwords for the offline
 * X-ASR engine. Compares greedy decoding (the app today), plain beam search, and beam search with
 * the vocabulary as hotwords in several forms.
 *
 * [namesDir]: sentences full of names and places (testdata/hotwords/generate_names.ps1), scored for
 * CER, how many vocabulary words in the reference come out right, and vocabulary words that show
 * up where nobody said them. [dialogsDir]: multi-turn dialogs for latency (vocabulary unrelated).
 */
fun hotwordsTest(modelsDir: File, namesDir: File, dialogsDir: File, vocabulary: File, out: File) {
    val names = loadTruths(namesDir)
    require(names.isNotEmpty()) { "no files in $namesDir" }
    val dialogs = loadTruths(dialogsDir).filter { it.language == "zh-TW" && it.noise == "clean" }
    val words = vocabulary.readLines(Charsets.UTF_8).map { it.trim().removePrefix("﻿") }.filter { it.isNotEmpty() && !it.startsWith("#") }
    val base = EngineSetup(modelsDir)
    val sp = base.copy(hotwords = vocabulary, hotwordsSimplified = true, hotwordsSpaced = true)
    val setups = listOf(
        "Greedy (app today)" to base,
        "Beam search, no hotwords" to base.copy(beamSearch = true),
        "Hotwords as typed (Traditional), score 1.5" to base.copy(hotwords = vocabulary),
        "Hotwords → Simplified, not spaced, score 1.5" to base.copy(hotwords = vocabulary, hotwordsSimplified = true),
        "Hotwords → Simplified, one token per character, score 1.5" to sp,
        "Hotwords → Simplified, one token per character, score 2.5" to sp.copy(hotwordsScore = 2.5f),
        "Hotwords → Simplified, one token per character, score 4.0" to sp.copy(hotwordsScore = 4.0f),
    ).filter { (label, _) -> System.getenv("HOTWORDS_ONLY")?.let { only -> only.split(',').any { label.contains(it.trim()) } } ?: true }
    data class Row(val label: String, val names: List<FileResult>, val dialogs: List<FileResult>)
    val rows = setups.map { (label, s) ->
        System.err.println("== $label")
        runCatching {
            SherpaStack(s).use { st ->
                Row(label, names.map { runFile(st, it, namesDir, false) }, dialogs.map { runFile(st, it, dialogsDir, false) })
            }
        }.getOrElse { e ->
            System.err.println("   failed: ${e.message}")
            Row("$label (failed: ${e.message?.take(80)})", emptyList(), emptyList())
        }
    }

    fun count(text: String, w: String): Int {
        var n = 0
        var i = text.indexOf(w)
        while (i >= 0) { n++; i = text.indexOf(w, i + w.length) }
        return n
    }
    fun pct(x: Double) = if (x.isNaN()) "–" else String.format(Locale.ROOT, "%.1f%%", 100 * x)
    fun f2(x: Double) = if (x.isNaN()) "–" else String.format(Locale.ROOT, "%.2f", x)

    out.parentFile?.mkdirs()
    out.writeText(buildString {
        appendLine("# Custom vocabulary as offline hotwords")
        appendLine()
        appendLine("Generated by `:desktop --hotwords-test` on ${LocalDate.now()}. ${configLine(base)}")
        appendLine()
        appendLine("Vocabulary: ${words.size} words (${vocabulary.name}): names, places, shops; ${words.count { w -> names.none { t -> t.segments.any { it.text.contains(w) } } }} of them never occur (to catch false insertions).")
        appendLine("Names set: ${names.size} sentences (${names.map { it.id.substringAfter('_').substringBefore('_') }.distinct().size} TTS voices). Latency: ${dialogs.size} clean zh-TW TTS dialogs.")
        appendLine()
        appendLine("| Decoding | CER (names) | Vocabulary words right | Vocabulary words inserted wrongly | CER (dialogs) | First text p50 (s) | Line final p50 (s) | RTF |")
        appendLine("|---|---|---|---|---|---|---|---|")
        for (r in rows) {
            if (r.names.isEmpty()) { appendLine("| ${r.label} | – | – | – | – | – | – | – |"); continue }
            var refWords = 0
            var hits = 0
            var inserted = 0
            for (f in r.names) {
                val ref = f.truth.segments.joinToString("") { it.text }
                val hyp = f.captionText
                for (w in words) {
                    val inRef = count(ref, w)
                    val inHyp = count(hyp, w)
                    refWords += inRef
                    hits += minOf(inRef, inHyp)
                    inserted += maxOf(0, inHyp - inRef)
                }
            }
            val cerNames = r.names.sumOf { it.errors }.toDouble() / r.names.sumOf { it.refTokens }
            val cerDialogs = if (r.dialogs.isEmpty()) Double.NaN else r.dialogs.sumOf { it.errors }.toDouble() / r.dialogs.sumOf { it.refTokens }
            val all = r.names + r.dialogs
            appendLine(
                "| ${r.label} | ${pct(cerNames)} | $hits / $refWords (${pct(hits.toDouble() / refWords)}) | $inserted | ${pct(cerDialogs)} | " +
                    "${f2(percentile(r.dialogs.flatMap { it.firstPartialLatency }, 50.0))} | ${f2(percentile(r.dialogs.flatMap { it.finalLatency }, 50.0))} | " +
                    "${f2(all.map { it.rtf }.average())} |",
            )
        }
        appendLine()
        appendLine("Vocabulary words right: occurrences in the reference that also appear in the captions (Taiwan Traditional, after s2twp).")
    })
    System.err.println("wrote $out")
}
