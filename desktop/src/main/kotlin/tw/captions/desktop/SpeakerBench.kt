package tw.captions.desktop

import tw.captions.core.PipelineConfig
import java.io.File
import java.time.LocalDate
import java.util.Locale

/**
 * `--speaker-recluster`: live speaker labels vs regrouping all lines by voice afterwards (ADR-027),
 * with several similarity thresholds and with the true number of speakers given.
 */
fun speakerReclusterBenchmark(modelsDir: File, dir: File, out: File, quick: Boolean) {
    val all = loadTruths(dir).filter { f -> f.segments.none { it.speaker == "?" } && f.segments.map { it.speaker }.distinct().size >= 2 }
    val files = if (quick) all.groupBy { it.dialog.substringBefore('_') }.values.flatMap { it.take(3) } else all
    require(files.isNotEmpty()) { "no multi-speaker files in $dir" }
    val setup = EngineSetup(modelsDir, pipeline = PipelineConfig(vadEndpointSilenceSec = 0.6f, focusMarginDb = null), numThreads = 4)
    val variants: List<Pair<String, (Int) -> Pair<Float, Int>?>> = listOf(
        "Live only (now)" to { _ -> null },
        "Regroup, threshold 0.35" to { _ -> 0.35f to 0 },
        "Regroup, threshold 0.45" to { _ -> 0.45f to 0 },
        "Regroup, threshold 0.55" to { _ -> 0.55f to 0 },
        "Regroup, threshold 0.60" to { _ -> 0.60f to 0 },
        "Regroup, threshold 0.65" to { _ -> 0.65f to 0 },
        "Regroup, threshold 0.70" to { _ -> 0.70f to 0 },
        "Regroup, number of people given" to { n -> 0.45f to n },
    )
    val rows = mutableListOf<Pair<String, List<FileResult>>>()
    SherpaStack(setup).use { stack ->
        for ((label, cfg) in variants) {
            System.err.println("== $label")
            rows += label to files.map { t -> runFile(stack, t, dir, false, recluster = cfg(t.segments.map { it.speaker }.distinct().size)) }
        }
    }
    fun pct(x: Double) = if (x.isNaN()) "–" else String.format(Locale.ROOT, "%.1f%%", 100 * x)
    fun f1(x: Double) = String.format(Locale.ROOT, "%.1f", x)
    out.parentFile?.mkdirs()
    out.writeText(buildString {
        appendLine("# Speaker labels: live vs regrouped afterwards")
        appendLine()
        appendLine("Generated by `:desktop --speaker-recluster` on ${LocalDate.now()}. Offline engine with the iPhone settings (X-ASR 160 ms, CAM++, line end 0.6 s). " +
            "\"Regroup\" groups all finished lines by voice again (average linkage on cosine similarity) and keeps letters people already saw where possible. See ADR-027.")
        appendLine()
        appendLine("| Setup | Dataset | Files | Speaker accuracy | Speakers found / true (avg) |")
        appendLine("|---|---|---|---|---|")
        for ((label, rs) in rows) for ((ds, g) in rs.groupBy { it.truth.dialog.substringBefore('_') }) {
            val acc = g.map { it.speakerAcc }.filter { !it.isNaN() }.average()
            appendLine("| $label | $ds | ${g.size} | ${pct(acc)} | ${f1(g.map { it.speakers }.average())} / ${f1(g.map { r -> r.truth.segments.map { it.speaker }.distinct().size }.average())} |")
        }
    })
    System.err.println("wrote $out")
}
