package tw.captions.desktop

import tw.captions.core.PipelineConfig
import java.io.File
import java.time.LocalDate
import java.util.Locale

/**
 * `--speaker-recluster`: live speaker labels vs regrouping all lines by voice afterwards (ADR-027),
 * with several similarity thresholds and with the true number of speakers given.
 */
fun speakerReclusterBenchmark(modelsDir: File, dir: File, out: File, quick: Boolean) {
    val all = loadTruths(dir).filter { f -> f.segments.none { it.speaker == "?" } && f.segments.map { it.speaker }.distinct().size >= 2 }
    val files = if (quick) all.groupBy { it.dialog.substringBefore('_') }.values.flatMap { it.take(3) } else all
    require(files.isNotEmpty()) { "no multi-speaker files in $dir" }
    val setup = EngineSetup(modelsDir, pipeline = PipelineConfig(vadEndpointSilenceSec = 0.6f, focusMarginDb = null), numThreads = 4)
    // "End": regroup once when the recording is over. "App": regroup after every line and hand the
    // groups back to the live clustering, as the phone does; only this shows letters changing later.
    data class Variant(val label: String, val end: Pair<Float, Int>? = null, val app: Pair<Float, Int>? = null)
    val variants: List<Pair<Variant, (Int) -> Variant>> = buildList {
        add(Variant("Live only") to { _: Int -> Variant("Live only") })
        for (t in listOf(0.45f, 0.55f, 0.60f, 0.65f, 0.70f)) {
            add(Variant("End regroup $t") to { _: Int -> Variant("", end = t to 0) })
            add(Variant("App regroup $t") to { _: Int -> Variant("", app = t to 0) })
        }
        add(Variant("App regroup 0.55, number of people given") to { n: Int -> Variant("", app = 0.55f to n) })
    }
    val rows = mutableListOf<Pair<String, List<FileResult>>>()
    SherpaStack(setup).use { stack ->
        for ((v, cfg) in variants) {
            System.err.println("== ${v.label}")
            rows += v.label to files.map { t ->
                val c = cfg(t.segments.map { it.speaker }.distinct().size)
                runFile(stack, t, dir, false, recluster = c.end, appRegroup = c.app)
            }
        }
    }
    fun pct(x: Double) = if (x.isNaN()) "–" else String.format(Locale.ROOT, "%.1f%%", 100 * x)
    fun f1(x: Double) = String.format(Locale.ROOT, "%.1f", x)
    out.parentFile?.mkdirs()
    out.writeText(buildString {
        appendLine("# Speaker labels: live vs regrouped afterwards")
        appendLine()
        appendLine(configLine(setup))
        appendLine()
        appendLine("Generated by `:desktop --speaker-recluster` on ${LocalDate.now()}. Offline engine with X-ASR 160 ms, CAM++ and line end 0.6 s (config above). " +
            "\"Regroup\" groups all finished lines by voice again (average linkage on cosine similarity) and keeps letters people already saw where possible. See ADR-027.")
        appendLine()
        appendLine("| Setup | Dataset | Files | Speaker accuracy | Speakers found / true (avg) | Letter changes on shown lines (per file) |")
        appendLine("|---|---|---|---|---|---|")
        for ((label, rs) in rows) for ((ds, g) in rs.groupBy { it.truth.dialog.substringBefore('_') }) {
            val acc = g.map { it.speakerAcc }.filter { !it.isNaN() }.average()
            appendLine("| $label | $ds | ${g.size} | ${pct(acc)} | ${f1(g.map { it.speakers }.average())} / ${f1(g.map { r -> r.truth.segments.map { it.speaker }.distinct().size }.average())} | ${f1(g.map { it.labelFlips }.average())} |")
        }
    })
    System.err.println("wrote $out")
}
