package tw.captions.desktop

import tw.captions.core.SecondPass
import tw.captions.core.TextProcessor
import java.io.File
import java.time.LocalDate
import java.util.Locale

/**
 * `--second-pass-check`: is the second pass worse because of the models or because of how the
 * app feeds them? Each whole-sentence model hears every reference segment cut by the reference
 * timestamps (no VAD, no [SecondPass.choose]); text goes through the same s2twp processing as
 * captions. CER raw and with numbers in one form (SenseVoice writes Arabic digits with ITN on).
 * Also lists 10 lines from the live run: live text, second-pass text, what `choose` kept.
 */
fun secondPassCheck(modelsDir: File, dir: File, out: File) {
    val files = loadTruths(dir).filter { it.language == "zh-TW" }
    require(files.isNotEmpty()) { "no zh-TW files in $dir" }
    val processor = TextProcessor.default(converter = OpenCcTaiwan)
    fun pct(e: Int, n: Int) = if (n == 0) "–" else String.format(Locale.ROOT, "%.1f%%", 100.0 * e / n)
    data class Row(val model: String, val ds: String, val raw: Pair<Int, Int>, val num: Pair<Int, Int>)
    val rows = mutableListOf<Row>()
    val samples = StringBuilder()
    // Baseline: the live streaming model on the same segments.
    SherpaStack(EngineSetup(modelsDir)).use { stack ->
        System.err.println("== X-ASR 160 ms (live model)")
        for ((ds, group) in files.groupBy { datasetOf(it) }) {
            var e = 0; var n = 0; var en = 0; var nn = 0
            for (t in group) {
                val audio = readWav16k(File(dir, "wavs/${t.id}.wav"))
                for (s in t.segments) {
                    val a = (s.start * 16000).toInt().coerceIn(0, audio.size)
                    val b = (s.end * 16000).toInt().coerceIn(a, audio.size)
                    if (b - a < 1600) continue
                    val hyp = processor.process(decodeAll(stack, audio.copyOfRange(a, b)))
                    val ref = OpenCcTaiwan.toTraditional(s.text)
                    val r = scoringTokens(ref); val h = scoringTokens(hyp)
                    e += editDistance(r, h); n += r.size
                    val rn = scoringTokens(ref, NumberForm.ARABIC); val hn = scoringTokens(hyp, NumberForm.ARABIC)
                    en += editDistance(rn, hn); nn += rn.size
                }
            }
            rows += Row("X-ASR 160 ms (live model)", ds, e to n, en to nn)
        }
    }
    for (m in OfflineAsrModel.ALL) {
        if (m.dir(modelsDir) == null) continue
        System.err.println("== ${m.name}")
        SherpaOfflineAsr(m, modelsDir, numThreads = 4).use { asr ->
            for ((ds, group) in files.groupBy { datasetOf(it) }) {
                var e = 0; var n = 0; var en = 0; var nn = 0
                for (t in group) {
                    val audio = readWav16k(File(dir, "wavs/${t.id}.wav"))
                    for ((k, s) in t.segments.withIndex()) {
                        val a = (s.start * 16000).toInt().coerceIn(0, audio.size)
                        val b = (s.end * 16000).toInt().coerceIn(a, audio.size)
                        if (b - a < 1600) continue
                        val hyp = processor.process(asr.recognize(audio.copyOfRange(a, b)))
                        val ref = OpenCcTaiwan.toTraditional(s.text)
                        val r = scoringTokens(ref); val h = scoringTokens(hyp)
                        e += editDistance(r, h); n += r.size
                        val rn = scoringTokens(ref, NumberForm.ARABIC); val hn = scoringTokens(hyp, NumberForm.ARABIC)
                        en += editDistance(rn, hn); nn += rn.size
                        if (m == OfflineAsrModel.SENSE_VOICE_2024 && samples.lines().size < 12 && k % 7 == 3) {
                            samples.appendLine("| ${t.id} #$k | $ref | $hyp |")
                        }
                    }
                }
                rows += Row(m.name, ds, e to n, en to nn)
            }
        }
    }
    out.parentFile?.mkdirs()
    out.writeText(buildString {
        appendLine("# Second-pass models on reference segments (no VAD, no choose)")
        appendLine()
        appendLine("Generated by `:desktop --second-pass-check` on ${LocalDate.now()}. Every reference segment is cut by its timestamps and recognised alone; output goes through the same s2twp processing as captions.")
        appendLine()
        appendLine("| Model | Dataset | CER | CER (numbers as digits) |")
        appendLine("|---|---|---|---|")
        for (r in rows) appendLine("| ${r.model} | ${r.ds} | ${pct(r.raw.first, r.raw.second)} | ${pct(r.num.first, r.num.second)} |")
        appendLine()
        appendLine("## Sample lines (SenseVoice 2024)")
        appendLine()
        appendLine("| Segment | Reference | SenseVoice |")
        appendLine("|---|---|---|")
        append(samples)
    })
    System.err.println("wrote $out")
}
