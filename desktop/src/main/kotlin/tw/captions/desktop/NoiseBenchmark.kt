package tw.captions.desktop

import java.io.File
import java.time.LocalDate
import java.util.Locale
import java.util.concurrent.Executors

// Noise robustness: testdata/noise/make_noise_set.py builds datasets/noise_bench, this scores it.

private const val USABLE_CER = 0.15

/** Runs every noise-bench file with and without each denoiser and writes docs/benchmark-noise.md. */
fun noiseBenchmark(modelsDir: File, dir: File, out: File, quick: Boolean = false) {
    val truths = loadTruths(dir)
    require(truths.isNotEmpty()) { "no files in $dir; run testdata/noise/make_noise_set.py" }
    val base = EngineSetup(modelsDir)
    val setups = if (quick) listOf(base) else listOf(base, base.copy(denoiser = DenoiserModel.GTCRN), base.copy(denoiser = DenoiserModel.DPDFNET2))
    // The three configurations run side by side (one thread each) so the run finishes in reasonable
    // time; latency includes that CPU contention, so it is a little pessimistic.
    val pool = Executors.newFixedThreadPool(setups.size)
    val futures = setups.map { setup ->
        pool.submit<Pair<EngineSetup, List<FileResult>>> {
            System.err.println("== ${setup.label} (${truths.size} files)")
            SherpaStack(setup).use { stack -> setup to truths.map { runFile(stack, it, dir, false) } }
        }
    }
    val results = futures.map { it.get() }
    pool.shutdown()
    val sample = readWav16k(File(dir, "wavs/${truths.first { it.noise == "clean" }.id}.wav"))
    val denoiserRtf = DenoiserModel.entries.associateWith { m -> denoiserRtf(m, modelsDir, sample) }
    out.parentFile.mkdirs()
    out.writeText(noiseReport(results, denoiserRtf))
    System.err.println("wrote $out")
}

/** Compute time of the denoiser alone, single thread, relative to audio time. */
fun denoiserRtf(model: DenoiserModel, modelsDir: File, audio: FloatArray): Double =
    SherpaDenoiser(model, modelsDir, numThreads = 1).use { d ->
        repeat(3) { d.process(audio.copyOfRange(0, minOf(audio.size, 1600))) } // warm up
        d.reset()
        val t0 = System.nanoTime()
        var i = 0
        while (i < audio.size) {
            val n = minOf(1600, audio.size - i)
            d.process(audio.copyOfRange(i, i + n))
            i += n
        }
        (System.nanoTime() - t0) / 1e9 / (audio.size / 16000.0)
    }

private fun p1(x: Double) = if (x.isNaN()) "–" else String.format(Locale.ROOT, "%.0f%%", 100 * x)
private fun d2(x: Double) = if (x.isNaN()) "–" else String.format(Locale.ROOT, "%.2f", x)

private fun cer(rs: List<FileResult>) = if (rs.isEmpty()) Double.NaN else rs.sumOf { it.errors }.toDouble() / rs.sumOf { it.refTokens }.coerceAtLeast(1)

private fun spk(rs: List<FileResult>): Double {
    val w = rs.filter { !it.speakerAcc.isNaN() }
    return if (w.isEmpty()) Double.NaN else w.sumOf { it.speakerAcc * it.refTokens } / w.sumOf { it.refTokens }
}

fun noiseReport(results: List<Pair<EngineSetup, List<FileResult>>>, denoiserRtf: Map<DenoiserModel, Double>): String = buildString {
    fun name(s: EngineSetup) = s.denoiser?.label ?: "none"
    val kinds = listOf("babble", "restaurant", "street", "kitchen", "tv", "reverb_cafe")
    val snrs = listOf(20, 15, 10, 5, 0, -5)
    val speechFiles = results.first().second.filter { !it.truth.id.startsWith("noiseonly__") }
    appendLine("# Noise robustness (sherpa-onnx engine)")
    appendLine()
    appendLine("Generated by `:desktop` on ${LocalDate.now()} (${System.getProperty("os.name")}, ${Runtime.getRuntime().availableProcessors()} logical CPUs). " +
        "Engine: ${results.first().first.label}. Regenerate with:")
    appendLine()
    appendLine("```")
    appendLine("python testdata/noise/make_noise_set.py datasets")
    appendLine("./gradlew :desktop:run --args=\"--models <model dir> --noise datasets/noise_bench\"")
    appendLine("```")
    appendLine()
    val cleanMin = speechFiles.filter { it.truth.noise == "clean" }.sumOf { it.truth.duration } / 60
    appendLine("Speech is Taiwan-accent only: 4 Common Voice zh-TW two-speaker sessions and 2 zh-TW TTS dialogs (${d2(cleanMin)} min), " +
        "each mixed with every noise at every SNR (measured over the speech-active parts). Three runs: no denoiser, GTCRN, DPDFNet-2 " +
        "(sherpa-onnx streaming speech enhancement in front of VAD, recognition and speaker embeddings).")
    appendLine()
    appendLine("| Noise | Source | License |")
    appendLine("|---|---|---|")
    appendLine("| babble | 8 overlapping Taiwan-accent talkers (other Common Voice zh-TW speakers) | CC0 |")
    appendLine("| restaurant | [DEMAND](https://zenodo.org/records/1227121) PRESTO, real recording | CC BY-SA 3.0 |")
    appendLine("| street | DEMAND STRAFFIC, real recording | CC BY-SA 3.0 |")
    appendLine("| kitchen | DEMAND DKITCHEN (dishes, appliances), real recording | CC BY-SA 3.0 |")
    appendLine("| tv | a Common Voice talker over background music by Kevin MacLeod ([incompetech](https://incompetech.com)) at −6 dB | CC0, CC BY 4.0 |")
    appendLine("| reverb_cafe | speech convolved with a real room impulse response ([OpenSLR SLR28](https://www.openslr.org/28/)) + DEMAND PCAFETER cafeteria | Apache 2.0, CC BY-SA 3.0 |")
    appendLine()
    appendLine("## Denoiser cost")
    appendLine()
    appendLine("| Denoiser | RTF of the denoiser alone (1 thread, this PC) | Model size |")
    appendLine("|---|---|---|")
    for ((m, rtf) in denoiserRtf) appendLine("| ${m.label} | ${d2(rtf)} | ${if (m == DenoiserModel.GTCRN) "0.5 MB" else "10 MB"} |")
    appendLine()
    appendLine("A phone CPU core is roughly 3–5× slower than this PC, so the denoiser must stay well under 0.1 here to leave time for recognition.")
    appendLine()

    for ((title, metric) in listOf<Pair<String, (List<FileResult>) -> Double>>("Character error rate" to ::cer, "Speaker-tag accuracy" to ::spk)) {
        appendLine("## $title by noise and SNR")
        appendLine()
        appendLine("Each cell: " + results.joinToString(" / ") { name(it.first) } + " denoiser.")
        appendLine()
        appendLine("| Noise | clean | " + snrs.joinToString(" | ") { "$it dB" } + " |")
        appendLine("|---|---|" + snrs.joinToString("") { "---|" })
        for (k in kinds) {
            if (speechFiles.none { it.truth.noise == k }) continue
            val cells = mutableListOf(results.joinToString(" / ") { (_, rs) -> p1(metric(rs.filter { it.truth.noise == "clean" })) })
            for (snr in snrs) cells += results.joinToString(" / ") { (_, rs) -> p1(metric(rs.filter { it.truth.noise == k && it.truth.snr == snr })) }
            appendLine("| $k | " + cells.joinToString(" | ") + " |")
        }
        appendLine()
    }

    appendLine("## Latency in noise")
    appendLine()
    appendLine("All noise types together. Each cell: " + results.joinToString(" / ") { name(it.first) } + ".")
    appendLine()
    appendLine("| SNR | First partial p50 (s) | Final p50 (s) |")
    appendLine("|---|---|---|")
    for (snr in listOf<Int?>(null) + snrs) {
        val row = results.map { (_, rs) -> rs.filter { if (snr == null) it.truth.noise == "clean" else it.truth.snr == snr } }
        appendLine("| ${snr?.let { "$it dB" } ?: "clean"} | ${row.joinToString(" / ") { d2(percentile(it.flatMap { r -> r.firstPartialLatency }, 50.0)) }} | " +
            "${row.joinToString(" / ") { d2(percentile(it.flatMap { r -> r.finalLatency }, 50.0)) }} |")
    }
    appendLine()

    appendLine("## Noise only: phantom captions")
    appendLine()
    appendLine("3 minutes of loud noise (about −20 dBFS) with nobody speaking to the user. Every caption line here is a phantom, " +
        "and someone relying on the captions cannot tell it from real speech.")
    appendLine()
    appendLine("| Noise | " + results.joinToString(" | ") { "${name(it.first)}: lines / chars / speakers" } + " | Example phantom lines (no denoiser) |")
    appendLine("|---|" + results.joinToString("") { "---|" } + "---|")
    for (k in listOf("babble", "tv", "music", "restaurant", "street")) {
        val per = results.map { (_, rs) -> rs.firstOrNull { it.truth.id == "noiseonly__$k" } }
        if (per.all { it == null }) continue
        val cells = per.joinToString(" | ") { r ->
            if (r == null) "–" else "${r.utterances.size} / ${r.utterances.sumOf { scoringTokens(it.text).size }} / ${r.speakers}"
        }
        val examples = per.first()?.utterances?.take(4)?.joinToString(" · ") { it.text.replace("|", "\\|") }.orEmpty()
        appendLine("| $k | $cells | $examples |")
    }
    appendLine()

    appendLine("## Lowest SNR with usable captions (CER < ${(USABLE_CER * 100).toInt()}%)")
    appendLine()
    appendLine("| Noise | " + results.joinToString(" | ") { name(it.first) } + " |")
    appendLine("|---|" + results.joinToString("") { "---|" })
    for (k in kinds) {
        if (speechFiles.none { it.truth.noise == k }) continue
        appendLine("| $k | " + results.joinToString(" | ") { (_, rs) ->
            // Usable down to the lowest SNR before the first SNR that fails.
            var lowest: Int? = null
            for (snr in snrs) {
                if (cer(rs.filter { it.truth.noise == k && it.truth.snr == snr }) < USABLE_CER) lowest = snr else break
            }
            lowest?.let { "$it dB" } ?: "> 20 dB"
        } + " |")
    }
    appendLine()
}

/** Share of speech time (union of all turns) during which two or more people talk. */
fun overlapShare(t: Truth): Double {
    val step = 0.05
    val end = t.segments.maxOfOrNull { it.end } ?: return Double.NaN
    var speech = 0
    var overlap = 0
    var x = 0.0
    while (x < end) {
        val n = t.segments.count { it.start <= x && x < it.end }
        if (n >= 1) speech++
        if (n >= 2) overlap++
        x += step
    }
    return if (speech == 0) Double.NaN else overlap.toDouble() / speech
}


/**
 * Focus filter (hide speech much quieter than the conversation): off vs several margins, on clean
 * speech, the noises with other voices (TV, babble) and restaurant, and the noise-only files.
 */
fun focusSweep(modelsDir: File, dir: File, out: File) {
    val all = loadTruths(dir)
    val files = all.filter { t ->
        t.id.startsWith("noiseonly__") || t.noise == "clean" ||
            (t.noise in setOf("tv", "babble", "restaurant") && t.snr in setOf(20, 10, 5, 0))
    }
    val base = EngineSetup(modelsDir, hideBackground = true)
    val setups = listOf(
        base.copy(pipeline = tw.captions.core.PipelineConfig(focusMarginDb = null)),
        base.copy(pipeline = tw.captions.core.PipelineConfig(focusMarginDb = 6f)),
        base.copy(pipeline = tw.captions.core.PipelineConfig(focusMarginDb = 8f)),
        base.copy(pipeline = tw.captions.core.PipelineConfig(focusMarginDb = 10f)),
    )
    val pool = Executors.newFixedThreadPool(setups.size)
    val results = setups.map { s -> pool.submit<Pair<EngineSetup, List<FileResult>>> { SherpaStack(s).use { st -> s to files.map { runFile(st, it, dir, false) } } } }
        .map { it.get() }
    pool.shutdown()
    fun name(s: EngineSetup) = s.pipeline.focusMarginDb?.let { "${it.toInt()} dB" } ?: "off"
    out.parentFile.mkdirs()
    out.writeText(buildString {
        appendLine("# Focus filter: hide speech much quieter than the conversation")
        appendLine()
        appendLine("Generated by `:desktop --focus-sweep` on ${LocalDate.now()}. Same Taiwan-accent noise set as [benchmark-noise.md](benchmark-noise.md). " +
            "A finished line is hidden when its speech level is more than the margin below the conversation's recent level (`FocusTracker`). " +
            "Cells: " + results.joinToString(" / ") { name(it.first) } + ".")
        appendLine()
        appendLine("## CER of what is shown")
        appendLine()
        appendLine("| Condition | " + results.joinToString(" | ") { name(it.first) } + " |")
        appendLine("|---|" + results.joinToString("") { "---|" })
        val conds = listOf<Pair<String, (Truth) -> Boolean>>("clean" to { it.noise == "clean" }) +
            listOf("tv", "babble", "restaurant").flatMap { k -> listOf(20, 10, 5, 0).map { snr -> "$k $snr dB" to { t: Truth -> t.noise == k && t.snr == snr } } }
        for ((label, f) in conds) {
            appendLine("| $label | " + results.joinToString(" | ") { (_, rs) -> p1(cer(rs.filter { f(it.truth) && !it.truth.id.startsWith("noiseonly__") })) } + " |")
        }
        appendLine()
        appendLine("## Speaker-tag accuracy (clean)")
        appendLine()
        appendLine("| " + results.joinToString(" | ") { name(it.first) } + " |")
        appendLine("|" + results.joinToString("") { "---|" })
        appendLine("| " + results.joinToString(" | ") { (_, rs) -> p1(spk(rs.filter { it.truth.noise == "clean" })) } + " |")
        appendLine()
        appendLine("## Noise only: phantom lines shown (3 minutes, nobody talking to the user)")
        appendLine()
        appendLine("| Noise | " + results.joinToString(" | ") { name(it.first) } + " |")
        appendLine("|---|" + results.joinToString("") { "---|" })
        for (k in listOf("tv", "babble", "music", "restaurant", "street")) {
            appendLine("| $k | " + results.joinToString(" | ") { (_, rs) -> rs.firstOrNull { it.truth.id == "noiseonly__$k" }?.utterances?.size?.toString() ?: "–" } + " |")
        }
    })
    System.err.println("wrote $out")
}
